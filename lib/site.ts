/**
 * Starting price for a service, interpolated — never retyped. The FAQ below used to
 * hand-copy ₪150/₪190, so a price edit silently contradicted the /pricing/ table on the
 * same page (backlog §7.7). One source now: `services[].priceFrom`.
 */
const priceOf = (slug: string): string => getService(slug)?.priceFrom ?? "הצעת מחיר";

/**
 * The price as it should actually read on the page.
 *
 * `priceFrom` holds two different kinds of value: a real starting price (`₪150 למ״ר`) and
 * a "this one gets quoted" phrase (`הצעת מחיר לפי פרויקט`). Three call sites blindly
 * prefixed `החל מ-` to both, so three of the five rows on `/pricing/` — and the matching
 * service sidebars — shipped reading **"החל מ-הצעת מחיר לפי פרויקט"**. Only a value that
 * names a currency amount takes the prefix.
 */
export function priceLabel(priceFrom: string | undefined): string {
  if (!priceFrom) return "הצעת מחיר";
  return priceFrom.startsWith("₪") ? `החל מ-${priceFrom}` : priceFrom;
}

/**
 * Just the currency amount from a service's price — `"₪150 למ״ר"` → `"₪150"` — for compact
 * display like the hero stat tiles, where the unit lives in the tile's own label.
 *
 * Returns `null` for a quote-only service so the caller can drop the tile instead of
 * printing a sentence where a number belongs. Exists so nothing has to retype a price:
 * the hero had `₪150`/`₪190` as string literals, re-introducing the very duplication bug
 * `priceOf()` was written to kill (backlog §7.7).
 */
export function priceAmount(slug: string): string | null {
  const match = getService(slug)?.priceFrom?.match(/^₪[\d,]+/);
  return match ? match[0] : null;
}

